
const { BookCopy, Book, BorrowRecord, User } = require('../models');
const { createAuditLog } = require('./audit.service');

/**
 * Helper: Create audit entry
 */
function createAuditEntry(userId, action, description) {
  return createAuditLog({
    userId,
    action,
    description,
  });
}

/**
 * Add a single book copy
 */
async function createCopy({ bookId, accessionCode, status }, userId) {
  let copy;

  try {
    if (!bookId || !accessionCode) {
      const error = new Error('bookId và accessionCode là bắt buộc.');
      error.statusCode = 400;
      throw error;
    }

    copy = await BookCopy.create({
      bookId,
      accessionCode: accessionCode.trim(),
      status: status || 'available',
    });

  } catch (error) {

    // Create failed -> Write failure audit
    try {
      await createAuditEntry(
        userId,
        'copy_create_failed',
        `Failed to create copy for book ID ${bookId}. Reason: ${error.message}`
      );
    } catch (auditError) {
      console.error('Failed to save audit log:', auditError);
    }

    throw error;
  }

  // Create successful -> Write success audit
  try {
    await createAuditEntry(
      userId,
      'copy_create',
      `Successfully created copy ID ${copy.id}, accession code: ${copy.accessionCode}, book ID: ${bookId}`
    );
  } catch (auditError) {
    console.error('Failed to save audit log:', auditError);
  }

  return copy;
}

/**
 * Batch add multiple copies for a book
 */
async function createBatchCopies({
  bookId,
  codes,
  prefix,
  startNumber,
  quantity,
  status,
}, userId) {
  let result;

  try {
    if (!bookId) {
      const error = new Error('bookId là bắt buộc.');
      error.statusCode = 400;
      throw error;
    }

    let copyList = [];

    // Case 1: An explicit array of accession codes provided
    if (codes && Array.isArray(codes) && codes.length > 0) {
      copyList = codes
        .map((c) => String(c).trim())
        .filter((c) => c.length > 0)
        .map((code) => ({
          bookId,
          accessionCode: code,
          status: status || 'available',
        }));
    }

    // Case 2: Generated by prefix and quantity
    else if (prefix && quantity && Number(quantity) > 0) {
      const start = Number(startNumber) || 1;
      const count = Number(quantity);

      for (let i = 0; i < count; i++) {
        const num = start + i;
        const padded = String(num).padStart(3, '0');

        copyList.push({
          bookId,
          accessionCode: `${prefix.trim()}-${padded}`,
          status: status || 'available',
        });
      }
    } else {
      const error = new Error(
        'Vui lòng cung cấp danh sách mã hoặc tiền tố (prefix) và số lượng.'
      );
      error.statusCode = 400;
      throw error;
    }

    if (copyList.length === 0) {
      const error = new Error(
        'Không có mã bản sao hợp lệ nào được tạo.'
      );
      error.statusCode = 400;
      throw error;
    }

    // Check if any accessionCode already exists
    const existing = await BookCopy.findAll({
      where: {
        accessionCode: copyList.map((c) => c.accessionCode),
      },
    });

    if (existing.length > 0) {
      const dupes = existing
        .map((e) => e.accessionCode)
        .join(', ');

      const error = new Error(
        `Các mã kiểm kê sau đã tồn tại trong hệ thống: ${dupes}`
      );
      error.statusCode = 400;
      throw error;
    }

    // Create multiple copies
    const createdCopies = await BookCopy.bulkCreate(copyList);

    result = {
      message: `Đã nhập thành công ${createdCopies.length} bản sao.`,
      count: createdCopies.length,
      copies: createdCopies,
    };

  } catch (error) {

    // Batch create failed -> Write failure audit
    try {
      await createAuditEntry(
        userId,
        'copy_batch_create_failed',
        `Failed to create batch copies for book ID ${bookId}. Reason: ${error.message}`
      );
    } catch (auditError) {
      console.error('Failed to save audit log:', auditError);
    }

    throw error;
  }

  // Batch create successful -> Write success audit
  try {
    await createAuditEntry(
      userId,
      'copy_batch_create',
      `Successfully created ${result.count} copies for book ID ${bookId}`
    );
  } catch (auditError) {
    console.error('Failed to save audit log:', auditError);
  }

  return result;
}

/**
 * List all copies
 */
async function getAllCopies() {
  return await BookCopy.findAll({
    include: [
      {
        model: Book,
        attributes: ['id', 'title', 'isbn'],
      },
    ],
    order: [['id', 'DESC']],
  });
}

/**
 * List all copies of a specific book
 */
async function getCopiesByBookId(bookId) {
  return await BookCopy.findAll({
    where: { bookId },
    include: [
      {
        model: BorrowRecord,
        where: { status: 'borrowed' },
        required: false,
        include: [
          {
            model: User,
            as: 'user',
            attributes: ['id', 'username', 'fullName'],
          },
        ],
      },
    ],
    order: [['accessionCode', 'ASC']],
  });
}

/**
 * List copies of a book that a reader can request right now:
 * status = available AND no active (pending/approved/borrowed) borrow record.
 */
async function getBorrowableCopiesByBookId(bookId) {
  const copies = await BookCopy.findAll({
    where: {
      bookId,
      status: 'available',
    },
    attributes: ['id', 'bookId', 'accessionCode', 'status'],
    order: [['accessionCode', 'ASC']],
  });

  if (copies.length === 0) return [];

  const activeRecords = await BorrowRecord.findAll({
    where: {
      copyId: copies.map((c) => c.id),
      status: ['pending', 'approved', 'borrowed'],
    },
    attributes: ['copyId'],
  });

  const busyIds = new Set(
    activeRecords.map((r) => String(r.copyId))
  );

  return copies.filter(
    (c) => !busyIds.has(String(c.id))
  );
}

/**
 * Update copy status
 */
async function updateCopyStatus(id, status, userId) {
  let copy;
  let oldStatus;

  try {
    copy = await BookCopy.findByPk(id);

    if (!copy) {
      const error = new Error('Copy not found');
      error.statusCode = 404;
      throw error;
    }

    oldStatus = copy.status;

    await copy.update({ status });

  } catch (error) {

    // Update failed -> Write failure audit
    try {
      await createAuditEntry(
        userId,
        'copy_status_update_failed',
        `Failed to update status of copy ID ${id} to "${status}". Reason: ${error.message}`
      );
    } catch (auditError) {
      console.error('Failed to save audit log:', auditError);
    }

    throw error;
  }

  // Update successful -> Write success audit
  try {
    await createAuditEntry(
      userId,
      'copy_status_updated',
      `Successfully changed status of copy ID ${id} from "${oldStatus}" to "${status}"`
    );
  } catch (auditError) {
    console.error('Failed to save audit log:', auditError);
  }

  return copy;
}

/**
 * Delete a copy
 */
async function deleteCopy(id, userId) {
  let copy;

  try {
    copy = await BookCopy.findByPk(id);

    if (!copy) {
      const error = new Error('Không tìm thấy bản sao');
      error.statusCode = 404;
      throw error;
    }

    if (copy.status === 'borrowed') {
      const error = new Error(
        'Không thể xóa bản sao đang trong trạng thái được mượn!'
      );
      error.statusCode = 400;
      throw error;
    }

    // Delete copy
    await copy.destroy();

  } catch (error) {

    // Delete failed -> Write failure audit
    try {
      await createAuditEntry(
        userId,
        'copy_delete_failed',
        `Failed to delete copy ID ${id}. Reason: ${error.message}`
      );
    } catch (auditError) {
      console.error('Failed to save audit log:', auditError);
    }

    throw error;
  }

  // Delete successful -> Write success audit
  try {
    await createAuditEntry(
      userId,
      'copy_delete',
      `Successfully deleted copy ID ${id}. Accession code: ${copy.accessionCode}, book ID: ${copy.bookId}`
    );
  } catch (auditError) {
    console.error('Failed to save audit log:', auditError);
  }

  return {
    message: 'Đã xóa bản sao thành công.',
  };
}

module.exports = {
  createCopy,
  createBatchCopies,
  getAllCopies,
  getCopiesByBookId,
  getBorrowableCopiesByBookId,
  updateCopyStatus,
  deleteCopy,
};
