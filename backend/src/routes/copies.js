const express = require('express');
const router = express.Router();
const { BookCopy, Book, BorrowRecord, User } = require('../models');
const { authorize } = require('../middleware/auth');

// Add a single copy – admin or librarian
router.post('/', authorize('admin','librarian'), async (req, res) => {
  const { bookId, accessionCode, status } = req.body;
  try {
    const copy = await BookCopy.create({ bookId, accessionCode, status: status || 'available' });
    res.status(201).json(copy);
  } catch (e) {
    res.status(400).json({ error: e.message });
  }
});

// Batch add multiple copies for a book – admin or librarian
router.post('/batch', authorize('admin','librarian'), async (req, res) => {
  const { bookId, codes, prefix, startNumber, quantity, status } = req.body;
  try {
    let copyList = [];

    // Case 1: An explicit array of accession codes provided
    if (codes && Array.isArray(codes) && codes.length > 0) {
      copyList = codes
        .map(c => String(c).trim())
        .filter(c => c.length > 0)
        .map(code => ({
          bookId,
          accessionCode: code,
          status: status || 'available'
        }));
    } 
    // Case 2: Generated by prefix and quantity
    else if (prefix && quantity && Number(quantity) > 0) {
      const start = Number(startNumber) || 1;
      const count = Number(quantity);
      for (let i = 0; i < count; i++) {
        const num = start + i;
        const padded = String(num).padStart(3, '0');
        copyList.push({
          bookId,
          accessionCode: `${prefix.trim()}-${padded}`,
          status: status || 'available'
        });
      }
    } else {
      return res.status(400).json({ error: 'Vui lòng cung cấp danh sách mã hoặc tiền tố (prefix) và số lượng.' });
    }

    if (copyList.length === 0) {
      return res.status(400).json({ error: 'Không có mã bản sao hợp lệ nào được tạo.' });
    }

    // Check if any accessionCode already exists
    const existing = await BookCopy.findAll({
      where: { accessionCode: copyList.map(c => c.accessionCode) }
    });
    if (existing.length > 0) {
      const dupes = existing.map(e => e.accessionCode).join(', ');
      return res.status(400).json({ error: `Các mã kiểm kê sau đã tồn tại trong hệ thống: ${dupes}` });
    }

    const createdCopies = await BookCopy.bulkCreate(copyList);
    res.status(201).json({
      message: `Đã nhập thành công ${createdCopies.length} bản sao.`,
      count: createdCopies.length,
      copies: createdCopies
    });
  } catch (e) {
    res.status(400).json({ error: e.message });
  }
});

// List all copies
router.get('/', async (req, res) => {
  try {
    const copies = await BookCopy.findAll({
      include: [{ model: Book, attributes: ['id', 'title', 'isbn'] }],
      order: [['id', 'DESC']]
    });
    res.json(copies);
  } catch (e) {
    res.status(500).json({ error: e.message });
  }
});

// List all copies of a specific book
router.get('/book/:bookId', async (req, res) => {
  try {
    const copies = await BookCopy.findAll({
      where: { bookId: req.params.bookId },
      include: [
        {
          model: BorrowRecord,
          where: { status: 'borrowed' },
          required: false,
          include: [{ model: User, as: 'user', attributes: ['id', 'username', 'fullName'] }]
        }
      ],
      order: [['accessionCode', 'ASC']]
    });
    res.json(copies);
  } catch (e) {
    res.status(500).json({ error: e.message });
  }
});

// Update copy status – admin/librarian
router.put('/:id', authorize('admin','librarian'), async (req, res) => {
  const { status } = req.body;
  try {
    const copy = await BookCopy.findByPk(req.params.id);
    if (!copy) return res.status(404).json({ message: 'Copy not found' });
    await copy.update({ status });
    res.json(copy);
  } catch (e) {
    res.status(400).json({ error: e.message });
  }
});

// Delete a copy – admin/librarian
router.delete('/:id', authorize('admin','librarian'), async (req, res) => {
  try {
    const copy = await BookCopy.findByPk(req.params.id);
    if (!copy) return res.status(404).json({ message: 'Không tìm thấy bản sao' });
    if (copy.status === 'borrowed') {
      return res.status(400).json({ message: 'Không thể xóa bản sao đang trong trạng thái được mượn!' });
    }
    await copy.destroy();
    res.json({ message: 'Đã xóa bản sao thành công.' });
  } catch (e) {
    res.status(500).json({ error: e.message });
  }
});

module.exports = router;
